#!/usr/bin/env python3
"""
Daily portion sender for the RLCF Bible study plan.
------------------------------------------------------
Run once per day, Monday through Saturday. Finds the most recent
week-*.json file generated by generate_study_plan.py, figures out which
day of the week it is, and delivers just that day's portion via
responsive HTML email (with plain-text fallback) and Slack Block Kit.

Sundays are skipped on purpose — that's service day, and it's also when
generate_study_plan.py runs to build the upcoming week's plan.

Flags:
  --preview      Generate output/preview_today.html and open in web browser
  --day DAY      Override day of week to send/preview (e.g. Monday, Tuesday)
  --dry-run      Print output without actually sending email or posting to Slack

Environment variables required (email delivery):
  SMTP_HOST, SMTP_PORT, SMTP_USER, SMTP_PASS, EMAIL_TO, EMAIL_FROM

Optional (also posts to Slack alongside the email):
  SLACK_WEBHOOK_URL
"""

