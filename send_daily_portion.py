OUTPUT_DIR = os.path.join(os.path.dirname(__file__), "output")
DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"]
APP_URL = "https://davelane26.github.io/devotional-companion/"


def load_dotenv(filepath=".env"):
    """Optionally load environment variables from a local .env file."""
    target = filepath if os.path.isabs(filepath) else os.path.join(os.path.dirname(__file__), filepath)
    if not os.path.exists(target):
        return
    try:
        with open(target, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                k = k.strip()
                v = v.strip().strip("'\"")
                if k and k not in os.environ:
                    os.environ[k] = v
    except Exception as e:
        print(f"Warning: could not read {target}: {e}")


load_dotenv()


def bible_gateway_url(ref, version=None):
    """Generate a direct BibleGateway passage link."""
    v = version or os.environ.get("BIBLE_TRANSLATION", "NASB1995")
    clean_ref = ref.strip()
    encoded = urllib.parse.quote_plus(clean_ref)
    return f"https://www.biblegateway.com/passage/?search={encoded}&version={v}"


def get_latest_week_file():
    """Find the most recently generated week-*.json file."""
    pattern = os.path.join(OUTPUT_DIR, "week-*.json")
    matches = sorted(glob.glob(pattern), reverse=True)
    if not matches:
        raise RuntimeError("No week-*.json plan found in output/. "
                           "Has generate_study_plan.py run yet this week?")
    return matches[0]


def get_entry_for_day(week_data, target_day=None):
    """Pick out a specific day's block from the week's plan. Returns (entry, day_name)."""
    day_name = target_day or datetime.now().strftime("%A")
    if day_name not in DAYS:
        return None, day_name

    for entry in week_data.get("days", []):
        if entry.get("day") == day_name:
            return entry, day_name

    return None, day_name


def get_today_book_chapter(target_date_str=None):
    """Fetch today's Book Study chapter from book-schedule.json (graceful fallback)."""
    try:
        url = "https://davelane26.github.io/book-study-plan/output/book-schedule.json"
        resp = requests.get(url, timeout=8)
        if resp.status_code == 200:
            data = resp.json()
            query_date = target_date_str or datetime.now().strftime("%Y-%m-%d")
            item = data.get("schedule", {}).get(query_date)
            if item and item.get("chapters"):
                ch = item["chapters"][0]
                return {
                    "number": ch.get("number"),
                    "title": ch.get("title"),
                    "author": data.get("book_author", "Zac Poonen"),
                    "book_title": data.get("book_title", "Basic Christian Teachings"),
                }
    except Exception as e:
        print(f"Note: Could not fetch book study schedule: {e}")
    return None


def format_email_body(week_data, entry, today_name, book_chapter=None):
    """Plain-text email body (and fallback for non-HTML email clients)."""
    lines = [
        f"{today_name}'s Bible Study",
        "=" * (len(today_name) + 15),
        "",
        f"📱 Devotional Companion App: {APP_URL}",
        "",
        f"This week's memory verse: {week_data.get('memory_verse', '')}",
        f"From Sunday's message: {week_data.get('sermon_title', '')}",
        f"Sermon Link: {week_data.get('sermon_url', '')}",
        "",
        f"FOCUS: {entry.get('focus', '')}",
        "",
        f"READ: {'; '.join(entry.get('passages', []))}",
        "",
        f"MESSAGE RECAP: {entry.get('message_recap', '')}",
        "",
        f"QUOTE FROM THE MESSAGE: \"{entry.get('message_quote', '')}\"",
    ]

    rel = entry.get("related_scripture")
    if rel:
        lines.extend([
            "",
            f"TIES TO THE MEMORY VERSE: {rel}",
        ])

    if book_chapter:
        lines.extend([
            "",
            "--------------------------------------------------",
            f"📚 TODAY'S COMPANION BOOK STUDY: Chapter {book_chapter['number']}: {book_chapter['title']}",
            f"From '{book_chapter['book_title']}' by {book_chapter['author']}",
            f"Listen with follow-along audio in the app: {APP_URL}",
            "--------------------------------------------------",
        ])

    prayer = entry.get("daily_prayer")
    if prayer:
        lines.extend([
            "",
            f"TODAY'S PRAYER: {prayer}",
        ])

    lines.extend([
        "",
        "Open today's full study with Zac Poonen follow-along audio & reflection notes:",
        f"{APP_URL}",
    ])

    return "\n".join(lines)


