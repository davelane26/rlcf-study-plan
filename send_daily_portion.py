def format_slack_message(week_data, entry, today_name, book_chapter=None, translation=None):
    """Generate Slack Block Kit payload with rich mrkdwn and direct app links."""
    passages_text = " • ".join([f"<{bible_gateway_url(p, version=translation)}|*{p}*>" for p in entry.get("passages", [])])
    rel_scripture = entry.get("related_scripture", "")
    rel_text = f"<{bible_gateway_url(rel_scripture, version=translation)}|*{rel_scripture}*>" if rel_scripture else ""

    mem_verse = week_data.get('memory_verse', '')
    sermon_title = week_data.get('sermon_title', '')
    sermon_url = week_data.get('sermon_url', '#')

    blocks = [
        {
            "type": "header",
            "text": {
                "type": "plain_text",
                "text": f"📖 {today_name}'s Bible Study: {entry.get('focus', '')[:90]}",
                "emoji": True
            }
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*<https://davelane26.github.io/devotional-companion/|📱 Open in Devotional Companion App (Audio + Follow-Along + Journal) →>*"
            }
        },
        {
            "type": "context",
            "elements": [
                {
                    "type": "mrkdwn",
                    "text": f"*Memory Verse:* {mem_verse}\n*Sermon:* <{sermon_url}|{sermon_title}>"
                }
            ]
        },
        {"type": "divider"},
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Today's Scripture Reading:*\n{passages_text}"
            }
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Message Recap:*\n{entry.get('message_recap', '')}"
            }
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Quote from the Message:*\n> \"_{entry.get('message_quote', '')}_\""
            }
        },
    ]

    if rel_text:
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Ties to the Memory Verse:*\n{rel_text}"
            }
        })

    if book_chapter:
        b_num = book_chapter['number']
        b_title = book_chapter['title']
        b_book = book_chapter['book_title']
        b_auth = book_chapter['author']
        blocks.append({"type": "divider"})
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*📚 Today's Companion Book Study: Chapter {b_num}: {b_title}*\n_From '{b_book}' by {b_auth}_\n👉 *<https://davelane26.github.io/devotional-companion/|Listen with follow-along audio in the app →>*"
            }
        })

    prayer = entry.get("daily_prayer")
    if prayer:
        blocks.append({
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Today's Prayer:*\n_{prayer}_"
            }
        })

    fallback_text = (
        f"*{today_name}'s Bible Study: {entry.get('focus', '')}*\n"
        f"App: {APP_URL}\n"
        f"Read: {', '.join(entry.get('passages', []))}\n"
        f"Recap: {entry.get('message_recap', '')}"
    )

    return fallback_text, blocks


def send_slack(text, blocks=None):
    webhook_url = os.environ.get("SLACK_WEBHOOK_URL")
    if not webhook_url:
        print("SLACK_WEBHOOK_URL not set — skipping Slack delivery.")
        return

    payload = {"text": text}
    if blocks:
        payload["blocks"] = blocks

    resp = requests.post(webhook_url, json=payload, timeout=20)
    if resp.status_code != 200:
        raise RuntimeError(f"Slack webhook returned {resp.status_code}: {resp.text}")

    print("Posted today's portion to Slack (Block Kit formatted)")


def send_email(subject, plain_body, html_body=None):
    required = ["SMTP_HOST", "SMTP_PORT", "SMTP_USER", "SMTP_PASS", "EMAIL_TO", "EMAIL_FROM"]
    if not all(os.environ.get(v) for v in required):
        print("SMTP env vars not fully set — cannot send email.")
        return

    if html_body:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = os.environ["EMAIL_FROM"]
        msg["To"] = os.environ["EMAIL_TO"]
        msg.attach(MIMEText(plain_body, "plain", "utf-8"))
        msg.attach(MIMEText(html_body, "html", "utf-8"))
    else:
        msg = MIMEText(plain_body, "plain", "utf-8")
        msg["Subject"] = subject
        msg["From"] = os.environ["EMAIL_FROM"]
        msg["To"] = os.environ["EMAIL_TO"]

    host = os.environ["SMTP_HOST"]
    port = int(os.environ["SMTP_PORT"])
    user = os.environ["SMTP_USER"]
    password = os.environ["SMTP_PASS"]

    print(f"Connecting to SMTP server {host}:{port}...")
    with smtplib.SMTP(host, port, timeout=30) as server:
        server.ehlo()
        if port != 25:
            server.starttls()
            server.ehlo()
        server.login(user, password)
        server.send_message(msg)

    print(f"Email successfully sent to {os.environ['EMAIL_TO']}")


def parse_args():
    parser = argparse.ArgumentParser(description="Deliver or preview today's RLCF Bible study portion.")
    parser.add_argument("--preview", action="store_true", help="Generate HTML preview and open in browser")
    parser.add_argument("--day", type=str, choices=DAYS, help="Override today's day of week (e.g. Monday)")
    parser.add_argument("--translation", type=str, default=os.environ.get("BIBLE_TRANSLATION", "NASB1995"),
                        help="Bible translation for passage links (e.g. NASB1995, NKJV, ESV, NIV, KJV)")
    parser.add_argument("--dry-run", action="store_true", help="Format and print output without sending email or Slack")
    return parser.parse_args()


def main():
    args = parse_args()
    week_file = get_latest_week_file()
    with open(week_file, "r", encoding="utf-8") as f:
        week_data = json.load(f)

    entry, today_name = get_entry_for_day(week_data, target_day=args.day)

    if entry is None:
        print(f"Today is {today_name} — no portion to send "
              f"(Sunday is service day / plan-generation day).")
        return

    # Calculate date for today_name if --day was supplied
    target_date_str = None
    if args.day and week_data.get("week_of"):
        try:
            week_start = datetime.strptime(week_data["week_of"], "%Y-%m-%d")
            day_idx = DAYS.index(args.day)
            target_date_str = (week_start + timedelta(days=day_idx)).strftime("%Y-%m-%d")
        except Exception:
            pass

    book_chapter = get_today_book_chapter(target_date_str=target_date_str)

    plain_body = format_email_body(week_data, entry, today_name, book_chapter)
    html_body = format_email_html(week_data, entry, today_name, book_chapter, translation=args.translation)
    subject = f"Bible Study — {today_name}: {entry.get('focus', '')}"

    # Handle preview flag
    if args.preview:
        preview_path = os.path.join(OUTPUT_DIR, "preview_today.html")
        with open(preview_path, "w", encoding="utf-8") as f:
            f.write(html_body)
        print(f"Generated email preview: {preview_path}")
        webbrowser.open(f"file://{os.path.abspath(preview_path)}")

    if args.dry_run:
        print("\n=== DRY RUN MODE: Plain-Text Email ===")
        print(plain_body)
        print("\n=== DRY RUN MODE: Slack Fallback & Blocks ===")
        slack_text, slack_blocks = format_slack_message(week_data, entry, today_name, book_chapter, translation=args.translation)
        print(slack_text)
        print(f"Slack blocks count: {len(slack_blocks)}")
        print("\n=== DRY RUN MODE: HTML email generated successfully ===")
        return

    if not args.preview:
        send_email(subject, plain_body, html_body)
        slack_text, slack_blocks = format_slack_message(week_data, entry, today_name, book_chapter, translation=args.translation)
        send_slack(slack_text, slack_blocks)


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
